// Writes the SQL that fills in the tags of existing recipes from the same word lists the app suggests tags with
// (src/lib/recipeFacets.ts). Run once:  node --experimental-strip-types deploy/make-tags-sql.ts > supabase/migrations/…sql
import { ANIMAL, BASES, CUISINE_COUNTRY, MEAT, NOT, PROTEINS } from "../src/lib/recipeFacets.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const has = (w: string) => `t ~ ('(^|[^a-zäöüß])' || ${q(w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))})`;
const any = (words: string[]) => words.map(has).join(" or ");
const labels = (groups: [string, string[]][]) =>
  `array_remove(array[${groups.map(([l, ws]) => `case when ${any(ws)} then ${q(l)} end`).join(",\n    ")}]::text[], null)`;
const cleaned = NOT.reduce((acc, n) => `replace(${acc}, ${q(n)}, ' ')`, "lower(' ' || raw || ' ')");

console.log(`-- Recipe tags (base, protein, lifestyle, country), set when a recipe is created or edited. Existing recipes get
-- them filled in once from their ingredients, with the same word lists the app suggests tags with.
-- Generated by deploy/make-tags-sql.ts.
alter table public.recipes
  add column if not exists base_tags text[] not null default '{}',
  add column if not exists protein_tags text[] not null default '{}',
  add column if not exists lifestyle text check (lifestyle in ('Vegan', 'Vegetarian', 'Omnivore')),
  add column if not exists country text;
alter table public.cookbook_recipes
  add column if not exists base_tags text[] not null default '{}',
  add column if not exists protein_tags text[] not null default '{}',
  add column if not exists lifestyle text check (lifestyle in ('Vegan', 'Vegetarian', 'Omnivore'));

create or replace function pg_temp.recipe_tags(raw text)
returns table (base_tags text[], protein_tags text[], lifestyle text)
language sql immutable as $fn$
  select ${labels(BASES)},
    ${labels(PROTEINS)},
    case when ${any(MEAT)} then 'Omnivore' when ${any(ANIMAL)} then 'Vegetarian' else 'Vegan' end
  from (select ${cleaned} as t) x
$fn$;

update public.recipes r set base_tags = f.base_tags, protein_tags = f.protein_tags, lifestyle = f.lifestyle,
  country = coalesce(r.country, (
    select case lower(tag) ${Object.entries(CUISINE_COUNTRY).map(([k, v]) => `when ${q(k)} then ${q(v)}`).join(" ")} end
    from unnest(r.cuisine_tags) tag
    where lower(tag) in (${Object.keys(CUISINE_COUNTRY).map(q).join(", ")}) limit 1))
from (
  select r2.id, (pg_temp.recipe_tags(r2.name || ' | ' || coalesce((
    select string_agg(i.name, ' | ') from public.recipe_ingredients ri join public.ingredients i on i.id = ri.ingredient_id
    where ri.recipe_id = r2.id), ''))).*
  from public.recipes r2
) f
where f.id = r.id and r.lifestyle is null;

update public.cookbook_recipes c set base_tags = f.base_tags, protein_tags = f.protein_tags, lifestyle = f.lifestyle
from (
  select c2.id, (pg_temp.recipe_tags(c2.name || ' | ' || coalesce((
    -- ingredients is text[] in some projects and jsonb in others: to_jsonb reads both
    select string_agg(x, ' | ') from jsonb_array_elements_text(to_jsonb(c2.ingredients)) x), ''))).*
  from public.cookbook_recipes c2
) f
where f.id = c.id and c.lifestyle is null;`);
